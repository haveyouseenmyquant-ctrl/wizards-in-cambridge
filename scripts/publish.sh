#!/bin/bash
# Publish the current local build: pack the generated world data as a release asset; the release
# then publish.sh runs .github/workflows/pages.yml, which deploys viewer + world to GitHub Pages.
set -euo pipefail
cd "$(dirname "$0")/.."
# the Pages workflow deploys the viewer from git: refuse to publish with uncommitted changes
git diff --quiet HEAD -- site scripts || { echo "commit first: uncommitted changes in site/ or scripts/"; exit 1; }
# optimisation s8: fail fast before any release when build_hash.py would auto-hash app files missing from FILES: the
# URL hash can't list them, so the live-hash check after deploy fails (s48 deployed 895a9d5b over 2 unlisted Quest 5 files)
AUTO=$(.venv/bin/python -I scripts/build_hash.py site 2>&1 >/dev/null | grep 'auto-hash' || true)
[ -z "$AUTO" ] || { echo "not publishing: $AUTO (scripts/build_hash.py FILES)"; exit 1; }
# session 65: every browser module must parse as an ES module (s64 left a `}` inside a comment in mobs.js: the game
# layer silently failed to start and every mob/item/playtest test timed out)
for f in $(find site/app -name '*.js'); do cp "$f" /tmp/wc_check.mjs; node --check /tmp/wc_check.mjs || { echo "syntax error in $f"; exit 1; }; done
# session 75: digests of the collision and (QA s6) world tiles, part of build_hash.py (collision also of --game); shipped with the world tarball
.venv/bin/python -I scripts/collision_digest.py site
.venv/bin/python -I scripts/roof_match.py site   # roof_match_pct, cached per build hash
# game KPIs (mob/item/class tests + route bot), cached per build hash as data/benchmark/scores/<hash>_game.json
# WC_SKIP_GAME_KPI=1: leave it to service.sh (runs it for every new live hash) when a session is short of time
# session 63: wait (up to 45 min) for service.sh's run on the old live hash, else game_kpi.sh returns {} and the new
# live build goes out unscored (measure.sh then reads 0 for all six game KPIs until service.sh catches up)
[ -n "${WC_SKIP_GAME_KPI:-}" ] || for _ in $(seq 270); do [ -d /tmp/wc_game_kpi.lock ] || break; sleep 10; done
[ -n "${WC_SKIP_GAME_KPI:-}" ] || scripts/game_kpi.sh || echo "game_kpi.sh failed (service.sh retries for the live hash)"
# session 66: market_square_realism (main realism KPI) for the new build too, alongside the gameplay clip: sessions run
# back to back and service.sh pauses renders while one is active, so live builds were going out with no realism score
MSP=
if [ -z "${WC_SKIP_MS_BENCH:-}" ] && [ -f data/benchmark/market_square.json ]; then
  scripts/ms_bench.sh site > /tmp/wc_publish_ms.log 2>&1 & MSP=$!
fi
# session 64: gameplay_judged too (12-frame clip per class + judge), else measure.sh reads it as 0 until service.sh catches up
[ -n "${WC_SKIP_GAME_KPI:-}" ] || for _ in $(seq 180); do [ -d /tmp/wc_gameplay_kpi.lock ] || break; sleep 10; done
[ -n "${WC_SKIP_GAME_KPI:-}" ] || scripts/gameplay_kpi.sh || echo "gameplay_kpi.sh failed (service.sh retries for the live hash)"
[ -n "$MSP" ] && { wait $MSP && tail -n1 /tmp/wc_publish_ms.log || echo "ms_bench.sh failed (service.sh retries): $(tail -n2 /tmp/wc_publish_ms.log)"; }
# session 65: never push a build whose game layer is broken (game KPIs scored but mob_types 0)
if [ -z "${WC_SKIP_GAME_KPI:-}" ]; then
  GK=data/benchmark/scores/$(.venv/bin/python -I scripts/build_hash.py site --game)_game.json
  [ -s "$GK" ] && ! .venv/bin/python -I -c 'import json,sys; sys.exit(0 if json.load(open(sys.argv[1])).get("mob_types",0) > 0 else 1)' "$GK" && { echo "game KPIs read mob_types 0: not publishing"; exit 1; }
fi
TAG="world-$(date -u +%Y%m%d-%H%M)"
tar -czf /tmp/world.tar.gz -C site manifest.json landmarks.json tiles collision trees objects facades markings zone cityfac
ls -lh /tmp/world.tar.gz
git push origin HEAD
gh release create "$TAG" /tmp/world.tar.gz --title "World build $TAG" --notes "Generated by scripts/build.py. © OpenStreetMap contributors (ODbL); © Environment Agency copyright and/or database right 2022 (OGL v3)."
rm -f /tmp/world.tar.gz
# s4 (optimisation): fail fast with a clear status. Pages deploys hung for hours on 10 Nov (deploy-pages 'Current status'
# empty until timeout); pages.yml now retries the deploy once in-job, so publish.sh no longer reruns the whole run.
# WIC_PAGES_WAIT (s, default 1200) bounds the wait; afterwards the live URL must serve this build before live_site moves.
SITE_URL=https://haveyouseenmyquant-ctrl.github.io/wizards-in-cambridge/
HASH=$(.venv/bin/python -I scripts/build_hash.py site)
T0=$(date -u +%Y-%m-%dT%H:%M:%SZ)
gh workflow run pages.yml --ref main
RID=
for _ in $(seq 12); do sleep 5
  RID=$(gh run list --workflow pages.yml --limit 5 --json databaseId,createdAt -q "[.[]|select(.createdAt>=\"$T0\")][-1].databaseId")
  [ -n "$RID" ] && break; done
[ -n "$RID" ] || { echo "PUBLISH FAILED: no Pages run started (build $HASH released as $TAG, not live)"; exit 1; }
END=$(( $(date +%s) + ${WIC_PAGES_WAIT:-1200} )); ST=; CO=
while [ "$(date +%s)" -lt "$END" ]; do
  read -r ST CO < <(gh run view "$RID" --json status,conclusion -q '.status+" "+.conclusion' 2>/dev/null || echo "unknown -")
  [ "$ST" = completed ] && break; sleep 15; done
if [ "$ST" != completed ] || [ "$CO" != success ]; then
  echo "PUBLISH FAILED: Pages run $RID status=$ST conclusion=${CO:-none} (build $HASH released as $TAG, not live; live_site unchanged)"
  echo "  logs: gh run view $RID --log-failed | grep -v 'Current status' | tail"
  exit 1
fi
LIVE=
for _ in $(seq 24); do
  LIVE=$(.venv/bin/python -I scripts/build_hash.py "$SITE_URL" 2>/dev/null || true)
  [ "$LIVE" = "$HASH" ] && break; sleep 10; done
[ "$LIVE" = "$HASH" ] || { echo "PUBLISH FAILED: Pages run $RID ok but $SITE_URL serves ${LIVE:-nothing}, not $HASH (live_site unchanged)"; exit 1; }
echo "Pages run $RID ok: $SITE_URL serves $HASH"
# session 55: snapshot the published build (APFS clones, no extra disk) so service.sh can score the game KPIs of the
# live hash on it even while a session keeps editing site/
# session 56: wait (up to 30 min) for a running game_kpi/gameplay run so its snapshot isn't swapped out under it
for _ in $(seq 180); do [ -d /tmp/wc_game_kpi.lock ] || [ -d /tmp/wc_gameplay_kpi.lock ] || break; sleep 10; done
# QA: hold /tmp/wic_publish.lock while live_site is rewritten; service.sh skips scoring while it exists and drops
# (logs 'stale') any step whose build hash changed under it, so a half-copied live_site never gets scored
for _ in $(seq 60); do mkdir /tmp/wic_publish.lock 2>/dev/null && break; sleep 5; done
trap 'rm -rf /tmp/wic_publish.lock' EXIT
rm -rf data/derived/live_site.new && cp -c -R site data/derived/live_site.new && rm -rf data/derived/live_site && mv data/derived/live_site.new data/derived/live_site
rm -rf /tmp/wic_publish.lock
# session 58: the session is over once it publishes; let service.sh score the new live build
rm -f data/derived/session_active
